/*
 * Generate TS types from the committed contract JSON schemas.
 *
 *   npm run contract:gen     write frontend/src/lib/contract/{events,commands}.ts
 *   npm run contract:check   verify the on-disk files match a fresh generation
 *
 * The schemas themselves are produced by `python -m app.contract.export`.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { compile } from 'json-schema-to-typescript';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..', '..');
const SCHEMA_DIR = join(REPO_ROOT, 'app', 'contract', 'schema');
const OUT_DIR = join(__dirname, '..', 'src', 'lib', 'contract');

const BANNER =
  '/* GENERATED by app/contract — do not edit. Regenerate: python -m app.contract.export && npm run contract:gen */';

const TARGETS = [
  {
    title: 'SessionEvent',
    schema: join(SCHEMA_DIR, 'events.schema.json'),
    out: join(OUT_DIR, 'events.ts'),
  },
  {
    title: 'Command',
    schema: join(SCHEMA_DIR, 'commands.schema.json'),
    out: join(OUT_DIR, 'commands.ts'),
  },
];

const COMPILE_OPTIONS = {
  bannerComment: BANNER,
  style: { singleQuote: true },
};

async function generate(target) {
  const schema = JSON.parse(await readFile(target.schema, 'utf-8'));
  return compile(schema, target.title, COMPILE_OPTIONS);
}

async function main() {
  const check = process.argv.includes('--check');
  const results = await Promise.all(
    TARGETS.map(async (target) => ({ target, generated: await generate(target) }))
  );

  if (check) {
    const drift = [];
    for (const { target, generated } of results) {
      let current = null;
      try {
        current = await readFile(target.out, 'utf-8');
      } catch {
        current = null;
      }
      // Git checks these files out as CRLF on Windows; line endings are not
      // schema drift. Compare normalized text without rewriting the checkout.
      if (current?.replace(/\r\n/g, '\n') !== generated.replace(/\r\n/g, '\n')) {
        drift.push(target.out);
      }
    }
    if (drift.length > 0) {
      console.error(
        'Contract TS types are out of date:\n' +
          drift.map((f) => `  - ${f}`).join('\n') +
          '\nRegenerate with: python -m app.contract.export && npm run contract:gen'
      );
      process.exit(1);
    }
    console.log('Contract TS types are up to date.');
    return;
  }

  await mkdir(OUT_DIR, { recursive: true });
  for (const { target, generated } of results) {
    await writeFile(target.out, generated, 'utf-8');
    console.log(`Wrote ${target.out}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
