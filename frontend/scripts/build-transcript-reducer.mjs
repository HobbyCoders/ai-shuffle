#!/usr/bin/env node
/** Rebuild/check the checked-in server reducer; never compile on a worker boot. */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const frontend = fileURLToPath(new URL('../', import.meta.url));
const root = path.dirname(frontend.replace(/[\\/]$/, ''));
const destination = path.join(root, 'app/core/transcript_views');
const canonicalPaths = [
  'app/api/events.py', 'app/db/session_events.py', 'app/core/harness_reminders.py',
  'app/core/turn_recorder.py', 'app/core/transcript_views/preprocess.py'
];
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const canonicalSources = {};
for (const relative of canonicalPaths.sort()) {
  // Python's universal-newline semantics are identical in Windows checkouts.
  canonicalSources[relative] = digest((await readFile(path.join(root, relative), 'utf8')).replace(/\r\n/g, '\n'));
}
const options = {
  absWorkingDir: frontend,
  entryPoints: ['scripts/transcript-reducer-node.ts'],
  bundle: true, platform: 'node', format: 'cjs', target: ['node22'],
  write: false, legalComments: 'none', sourcemap: false, charset: 'utf8',
  tsconfigRaw: { compilerOptions: { baseUrl: '.', paths: { '$lib': ['./src/lib'], '$lib/*': ['./src/lib/*'] } } },
  banner: { js: '// Generated by frontend/scripts/build-transcript-reducer.mjs; do not edit.' }
};
const initial = await build({ ...options, define: { __TRANSCRIPT_REDUCER_FINGERPRINT__: JSON.stringify('fingerprint-input-v1') } });
const fingerprint = digest(Buffer.concat([initial.outputFiles[0].contents,
  Buffer.from('\0' + JSON.stringify(canonicalSources), 'utf8')]));
const generated = await build({ ...options, define: { __TRANSCRIPT_REDUCER_FINGERPRINT__: JSON.stringify(fingerprint) } });
const bundle = generated.outputFiles[0].text;
const manifest = JSON.stringify({ version: 1, fingerprint, bundle_sha256: digest(bundle),
  minimum_node_major: 22, canonical_sources: canonicalSources }, null, 2) + '\n';
const files = [['reducer.cjs', bundle], ['manifest.json', manifest]];
if (process.argv.includes('--check')) {
  for (const [name, expected] of files) {
    let actual;
    try { actual = await readFile(path.join(destination, name), 'utf8'); }
    catch { throw new Error(`Missing generated transcript reducer ${name}; run npm run transcript:build`); }
    if (actual !== expected) throw new Error(`Stale generated transcript reducer ${name}; run npm run transcript:build`);
  }
  console.log(`Transcript reducer matches ${fingerprint}`);
} else {
  await mkdir(destination, { recursive: true });
  for (const [name, content] of files) await writeFile(path.join(destination, name), content, 'utf8');
  console.log(`Built transcript reducer ${fingerprint} (${Buffer.byteLength(bundle, 'utf8')} bytes)`);
}
