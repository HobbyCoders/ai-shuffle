	 * Map a provider row (or the native sentinel) onto a glyph. The registry
	 * also emits legacy subscription rows stored as custom with a known auth mode.
	 */
	export function providerGlyphKind(providerType: string | null | undefined, authMode?: string | null): ProviderGlyphKind {
		if (providerType === 'custom') {
			if (authMode === 'chatgpt') return 'openai';
			if (authMode === 'grok') return 'grok';
		}
		switch (providerType) {
			case 'claude':
			case '__native__':
			case '__claude__':
				return 'claude';
			case 'anthropic':
				return 'anthropic';
			case 'openai':
			case 'chatgpt':
			case 'codex':
				return 'openai';
			case 'grok':
			case 'supergrok':
			case 'xai':
				return 'grok';
			case 'openrouter':
				return 'openrouter';
			case 'kimi':
			case 'minimax':
			case 'opencode':
			case 'google':
			case 'antigravity':
				return providerType;
			case 'fal':
			case 'fal-ai':
				return 'fal';
			default:
				return 'custom';
		}
	}
