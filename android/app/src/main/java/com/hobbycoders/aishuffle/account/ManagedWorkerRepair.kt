internal class WorkerRepairFailure(message: String) : IOException(message)
/** Never put a returned credential in an autogenerated data-class toString. */
internal class RepairedWorkerKey(val value: String)

/** This snapshot authorizes only replacing one existing worker's key, not its identity. */
internal class WorkerRepairSnapshot(context: Context, val server: Server) {
    private val accountStore = AccountStore(context)
    private val serverStore = ServerStore.get(context)
    private val account = accountStore.session() ?: throw WorkerRepairFailure("Sign in again before reconnecting this worker.")
    init {
        require(server.accountId == account.accountId && server.hubUrl == account.hub && server.deviceId == account.deviceId && !server.hubServerId.isNullOrBlank())
    }
    fun current() = accountStore.matches(account) && serverStore.getById(server.id) == server
    fun check() { if (!current()) throw WorkerRepairFailure("The account or worker changed. Open this worker again.") }
    fun save(key: RepairedWorkerKey) {
        check()
        if (serverStore.replaceKey(server, key.value) == null)
            throw WorkerRepairFailure("The worker changed or its key could not be saved. Retry reconnecting this worker.")
    }
}

internal object ManagedWorkerRepair {
    const val CAPABILITY = "scoped-v1"
    const val UPDATE_GUIDANCE = "Update this worker to support reconnecting an account device. Its current authorization has not been changed."
    private const val MAX_BODY = 8_192L
    private val client = OkHttpClient.Builder().followRedirects(false).followSslRedirects(false)
        .cookieJar(CookieJar.NO_COOKIES).cache(null).retryOnConnectionFailure(false)
        .connectTimeout(8, TimeUnit.SECONDS).readTimeout(15, TimeUnit.SECONDS).callTimeout(20, TimeUnit.SECONDS).build()

    internal fun scopedDeviceId(server: Server): String {
        fun identifier(value: String?): String {
            val text = value ?: throw IllegalArgumentException("Missing managed worker identity")
            require(UUID.fromString(text).toString() == text) { "Invalid managed worker identity" }
            return text
        }
        val worker = identifier(server.hubServerId)
        val phone = identifier(server.deviceId)
        val namespace = UUID.fromString("6ba7b811-9dad-11d1-80b4-00c04fd430c8")
        val bytes = ByteBuffer.allocate(16).putLong(namespace.mostSignificantBits).putLong(namespace.leastSignificantBits).array()
        val digest = MessageDigest.getInstance("SHA-1").apply {
            update(bytes); update("shuffle-account-device:$worker:$phone".toByteArray(Charsets.UTF_8))
        }.digest().copyOf(16)
        digest[6] = ((digest[6].toInt() and 0x0f) or 0x50).toByte()
        digest[8] = ((digest[8].toInt() and 0x3f) or 0x80).toByte()
        val buffer = ByteBuffer.wrap(digest)
        return UUID(buffer.long, buffer.long).toString()
    }

    internal fun request(server: Server, code: String? = null): Request {
        require(server.accountId != null && !server.hubServerId.isNullOrBlank())
        val origin = PairingInput.origin(server.baseUrl)
        require(origin == server.baseUrl)
        val builder = Request.Builder().url(origin + if (code == null) "/api/v1/mobile/hub/endpoint" else "/api/v1/mobile/register")
            .header("Accept", "application/json").header("Cache-Control", "no-cache, no-store")
        if (server.hasCfAccess) {
            builder.header("CF-Access-Client-Id", requireNotNull(server.cfAccessClientId))
            builder.header("CF-Access-Client-Secret", requireNotNull(server.cfAccessClientSecret))
        }
        if (code != null) {
            val info = JSONObject().put("device_id", scopedDeviceId(server)).put("device_name", "Android phone")
                .put("platform", "android").put("capabilities", JSONObject().put("supports_biometric", false)
                    .put("supports_push", false).put("biometric_types", org.json.JSONArray()))
            val body = JSONObject().put("account_repair", CAPABILITY).put("pairing_code", PairingInput.code(code)).put("device_info", info)
            builder.post(body.toString().toRequestBody("application/json; charset=utf-8".toMediaType()))
        }
        return builder.build()
    }

    internal fun checkSupport(server: Server, json: JSONObject) {
        if (json.opt("ready") != true || json.opt("protected_ingress") != true || json.opt("server_id") != server.hubServerId)
            throw WorkerRepairFailure("This address could not be verified as the selected worker. Refresh your workers before trying again.")
        if (json.opt("account_repair") != CAPABILITY) throw WorkerRepairFailure(UPDATE_GUIDANCE)
    }

    internal fun parseKey(server: Server, json: JSONObject, now: Instant = Instant.now()): RepairedWorkerKey {
        val key = json.opt("api_key") as? String
        val expiry = (json.opt("expires_at") as? String)?.let { runCatching { Instant.parse(it) }.getOrNull() }
        val scopes = json.optJSONArray("scopes")
        if (json.opt("device_id") != scopedDeviceId(server) || key == null ||
            !key.matches(Regex("aim_[A-Za-z0-9_-]{32,128}")) || key == server.apiKey || expiry == null || !expiry.isAfter(now) ||
            scopes == null || (0 until scopes.length()).any { scopes.opt(it) !is String } ||
            (0 until scopes.length()).none { scopes.opt(it) == "web:session" })
            throw WorkerRepairFailure("The worker returned an invalid repair response. Ask its administrator to prepare another repair and code.")
        return RepairedWorkerKey(key)
    }

    suspend fun verify(server: Server) { checkSupport(server, exchange(request(server))) }

    suspend fun repair(snapshot: WorkerRepairSnapshot, code: String): RepairedWorkerKey {
        snapshot.check()
        verify(snapshot.server)
        snapshot.check()
        val result = parseKey(snapshot.server, exchange(request(snapshot.server, code)))
        snapshot.check()
        verify(snapshot.server)
        snapshot.check()
        return result
    }

    private suspend fun exchange(request: Request): JSONObject = suspendCancellableCoroutine { continuation ->
        val call = client.newCall(request)
        continuation.invokeOnCancellation { call.cancel() }
        fun failed(message: String) { if (continuation.isActive) continuation.resumeWithException(WorkerRepairFailure(message)) }
        call.enqueue(object : Callback {
            override fun onFailure(call: Call, e: IOException) = failed("Connection interrupted. Your saved worker is unchanged. If the code was used, ask its administrator to prepare another repair and code.")
            override fun onResponse(call: Call, response: Response) {
                response.use {
                    try {
                        if (it.cacheResponse != null || it.request.url != request.url || it.isRedirect)
                            throw WorkerRepairFailure("This worker redirected the repair request. Refresh your workers before trying again.")
                        if (!it.isSuccessful || request.method == "GET" && it.code != 200) throw WorkerRepairFailure(when (it.code) {
                            404, 405 -> UPDATE_GUIDANCE
                            400, 401, 403, 409, 410 -> "This repair was not authorized or the code cannot be used. Ask this worker's administrator to prepare another repair and code."
                            429 -> "Too many attempts. Wait before trying a new repair code."
                            else -> "The worker could not complete the repair. Your saved connection is unchanged."
                        })
                        val body = it.body ?: throw IOException()
                        if (body.contentLength() > MAX_BODY) throw IOException()
                        val source = body.source()
                        source.request(MAX_BODY + 1)
                        if (source.buffer.size > MAX_BODY) throw IOException()
                        val json = JSONObject(source.readUtf8())
                        if (continuation.isActive) continuation.resume(json)
                    } catch (error: Exception) {
                        failed((error as? WorkerRepairFailure)?.message ?: "The worker returned an unsupported repair response. Ask its administrator to prepare another repair and code.")
                    }
                }
            }
        })
    }
}
